"""
Generate a synthetic, structurally valid `data_validate` input bundle.

Used to build larger-than-real-life fixtures for scale/performance testing (see
`.claude/rules/performance.md`, `tools/harness/profile_pipeline.py`). The generated bundle follows
the AdaptaBrasil spreadsheet protocol (see `.claude/skills/spreadsheet-protocol/SKILL.md`): a
`descricao`/`composicao` tree with one root indicator (`codigo` 1, `nivel` 1) and N-1 flat
children, a `valores` sheet covering every non-root `codigo-ano[-cenario]` combination (VAL-003
never allows a `nivel == 1` indicator any `valores` columns at all), `referencia_temporal`, and —
only when `--scenarios` is greater than zero — `cenarios`. `proporcionalidades`, `legenda` and
`dicionario` are intentionally not generated (optional sheets, not needed to exercise the pipeline
at scale) — every generated `valores` cell is therefore a 2-decimal string in `[0.01, 1.00]`,
matching LEG-015's protocol-default `[0, 1]` legend range that always applies when no `legenda`
sheet exists.

PERF-009: a bundle generated by this module validates with **0 errors** (verified at both a small
size — 20 indicators/3 years/2 scenarios/5 rows — and the performance budget's size — 6
indicators/5 years/3 scenarios/5000 rows, see `.specs/quality/performance.md`); only spell-check
warnings remain, from the synthetic pt-BR text. Note on scale: "5,000 indicators" in the
performance budget means 5,000 `valores` **rows** (territories), not 5,000 indicator codes as
columns — `FileStructureValidator`'s own structural size limit caps any sheet at 5,000 columns,
so `--indicators 5000` (which fans out into ~5,000 `codigo-ano[-cenario]` column groups) is
rejected by that limit before any business rule runs; pass a large `--rows` instead.

Writes `.xlsx` sheets when `openpyxl` is importable, otherwise falls back to `|`-separated `.csv`
(the protocol's other supported format).
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from datetime import date
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

_CSV_SEPARATOR = "|"
_ROOT_CODE = 1
"""int: `codigo` of the single root indicator (`nivel` 1) every generated bundle has."""


def _can_write_xlsx() -> bool:
    """Check whether `openpyxl` (pandas' `.xlsx` writer engine) is importable.

    Returns:
        bool: True if `.xlsx` sheets can be written, False if the CSV fallback is needed.
    """
    return importlib.util.find_spec("openpyxl") is not None


def _write_sheet(df: pd.DataFrame, out_dir: Path, base_name: str, *, use_xlsx: bool) -> Path:
    """Write one sheet to disk in the chosen format.

    Args:
        df: The sheet's data.
        out_dir: Destination directory.
        base_name: Sheet base name (e.g. `"descricao"`), without extension.
        use_xlsx: Whether to write `.xlsx` (True) or `|`-separated `.csv` (False).

    Returns:
        Path: The written file's path.
    """
    if use_xlsx:
        path = out_dir / f"{base_name}.xlsx"
        df.to_excel(path, index=False, engine="openpyxl")
    else:
        path = out_dir / f"{base_name}.csv"
        df.to_csv(path, sep=_CSV_SEPARATOR, index=False)
    return path


def _build_description(indicators: int, has_scenarios: bool) -> pd.DataFrame:
    """Build the `descricao` sheet: one root indicator plus N-1 flat children.

    Args:
        indicators: Total number of indicators (`codigo` 1..indicators). Indicator 1 is the root
            (`nivel` 1); the rest are its direct children (`nivel` 2).
        has_scenarios: Whether the dynamic `cenario` column should be included.

    Returns:
        pd.DataFrame: The `descricao` rows. When `has_scenarios` is True, every non-root row gets
            `cenario = 1` (VAL-003's "this indicator supports the full year/scenario grid"
            marker) so it lines up with `_build_values`'s columns; `cenario = 0` on a `nivel >= 2`
            row instead means "only the base-year column, no scenario grid" (VAL-002/VAL-003
            special-case it out of the code<->column comparison, which `_build_values` does not
            reproduce). The root's own `cenario` value is irrelevant — VAL-002/VAL-003 both gate
            their per-row scenario logic on `nivel >= 2`.
    """
    rows: list[dict[str, Any]] = []
    for codigo in range(1, indicators + 1):
        row: dict[str, Any] = {
            "codigo": codigo,
            "nivel": 1 if codigo == _ROOT_CODE else 2,
            "nome_simples": f"Indicador {codigo}",
            "nome_completo": f"Indicador completo {codigo}",
            "desc_simples": f"Descricao simples do indicador {codigo}.",
            "desc_completa": f"Descricao completa gerada automaticamente para o indicador sintetico {codigo}.",
            "fontes": "AdaptaBrasil synthetic fixture",
            "meta": "0.0",
            "unidade": "",
            "relacao": 1,
        }
        if has_scenarios:
            row["cenario"] = 0 if codigo == _ROOT_CODE else 1
        rows.append(row)
    return pd.DataFrame(rows)


def _build_composition(indicators: int) -> pd.DataFrame:
    """Build the `composicao` sheet: every indicator 2..N is a child of indicator 1.

    Args:
        indicators: Total number of indicators.

    Returns:
        pd.DataFrame: The `composicao` rows (empty when `indicators <= 1`).
    """
    if indicators <= 1:
        return pd.DataFrame(columns=["codigo_pai", "codigo_filho"])
    return pd.DataFrame({"codigo_pai": [1] * (indicators - 1), "codigo_filho": list(range(2, indicators + 1))})


def _build_temporal_reference(years: int, has_scenarios: bool) -> pd.DataFrame:
    """Build the `referencia_temporal` sheet.

    Per the protocol, a bundle without `cenarios` must have exactly one temporal reference row;
    `years` is honoured only when `has_scenarios` is True. `simbolo` is the actual calendar year
    (not a 0-based offset): `valores`' column names are built from `simbolo`
    (`CombinationsProcessing.generate_combinations`, `rules/value.py::check_value_combination_
    relation`), and TEMP-002 requires every `simbolo` but the first row to be `>= ` the current
    calendar year, so anchoring on `date.today().year` keeps the fixture valid regardless of when
    it is generated (no hardcoded year that becomes "past" over time).

    Args:
        years: Requested number of years.
        has_scenarios: Whether a `cenarios` sheet will also be generated.

    Returns:
        pd.DataFrame: The `referencia_temporal` rows.
    """
    count = years if has_scenarios else 1
    base_year = date.today().year
    rows = [
        {
            "nome": base_year + offset,
            "descricao": f"Ano de referencia {base_year + offset}.",
            "simbolo": base_year + offset,
        }
        for offset in range(max(count, 1))
    ]
    return pd.DataFrame(rows)


def _build_scenarios(scenarios: int) -> pd.DataFrame:
    """Build the `cenarios` sheet.

    Args:
        scenarios: Number of scenario symbols to generate (>= 1).

    Returns:
        pd.DataFrame: The `cenarios` rows.
    """
    rows = [
        {"nome": index, "descricao": f"Cenario sintetico {index}.", "simbolo": index}
        for index in range(1, scenarios + 1)
    ]
    return pd.DataFrame(rows)


def _build_values(
    indicators: int,
    temporal_df: pd.DataFrame,
    scenarios_df: pd.DataFrame | None,
    rows: int,
) -> pd.DataFrame:
    """Build the `valores` sheet: `rows` data rows, one column per `codigo-ano[-cenario]`.

    Reproduces exactly what VAL-003 (`rules/value.py::check_value_combination_relation`) expects
    for a `nivel >= 2` indicator with `cenario = 1` (see `_build_description`): one column for the
    base year (`temporal_df["simbolo"]`'s first value, no scenario suffix) plus one column per
    `(later simbolo, scenario symbol)` pair — `CombinationsProcessing.generate_combinations`'s own
    shape. The root indicator (`_ROOT_CODE`, `nivel` 1) gets **no** `valores` columns at all: a
    `nivel == 1` indicator is only ever allowed the columns VAL-003's `expected_combinations`
    computes for it (the empty list), so any `1-...` column is flagged as unnecessary
    (`rule.VAL-003.unnecessary_column_level1`).

    Every generated value is a 2-decimal string within `[0.01, 1.00]`, matching LEG-015's
    protocol-default `[0, 1]` legend range that applies whenever no `legenda` sheet is present
    (`rules/legend.py::check_value_range_within_legend`) — this bundle never generates one.

    Args:
        indicators: Total number of indicators.
        temporal_df: The generated `referencia_temporal` sheet (source of `simbolo` values).
        scenarios_df: The generated `cenarios` sheet, or None when no scenarios are configured.
        rows: Number of data rows (the `id` column).

    Returns:
        pd.DataFrame: The `valores` sheet.

    Note (PERF-009 harness perf, not the validated pipeline): built as one dense `numpy` object
    array, not a `dict[str, list]` handed straight to `pd.DataFrame`. pandas 3's default string
    dtype backs every object/string column with its own single-column `ExtensionBlock` — a
    dict-of-lists construction never consolidates those into one 2-D block, so `DataFrame.to_csv`
    ends up calling `get_values_for_csv` once per column. At 5 000 indicators x ~60 columns
    (≈ 300k `valores` columns) that made *generating* the fixture alone take about 48s (85s of it
    inside `to_csv`, per `cProfile` — `dev-reports/profile/`); building one `np.ndarray(dtype=
    object)` up front and handing pandas a single 2-D block instead cuts it to ~1s.
    """
    temporal_symbols = temporal_df["simbolo"].tolist()
    base_year = temporal_symbols[0]
    future_years = temporal_symbols[1:]
    scenario_symbols: list[int] = []
    if scenarios_df is not None and not scenarios_df.empty:
        scenario_symbols = scenarios_df["simbolo"].tolist()

    column_names: list[str] = ["id"]
    for codigo in range(_ROOT_CODE + 1, indicators + 1):
        column_names.append(f"{codigo}-{base_year}")
        for year in future_years:
            for symbol in scenario_symbols:
                column_names.append(f"{codigo}-{year}-{symbol}")

    # Every value column shares the same row-cycling `[0.01, 1.00]` pattern (only the row index
    # matters, not the column) — computed once and broadcast into every column's slice below,
    # instead of rebuilding an identical list per column.
    shared_values = [f"{(row_index % 100 + 1) / 100:.2f}" for row_index in range(rows)]

    array = np.empty((rows, len(column_names)), dtype=object)
    array[:, 0] = list(range(1, rows + 1))
    for column_index in range(1, len(column_names)):
        array[:, column_index] = shared_values
    return pd.DataFrame(array, columns=column_names, dtype="object")


def generate_fixture(indicators: int, years: int, scenarios: int, rows: int, out_dir: Path) -> list[Path]:
    """Generate a complete synthetic bundle under `out_dir`.

    Args:
        indicators: Number of indicators (`descricao`/`composicao` rows), >= 1.
        years: Number of temporal reference rows requested (only honoured when `scenarios > 0`).
        scenarios: Number of scenario symbols; 0 means no `cenarios` sheet is generated.
        rows: Number of data rows (the `id` column) in `valores`.
        out_dir: Destination directory; created if missing.

    Returns:
        list[Path]: Paths of every sheet written.

    Raises:
        ValueError: If any argument is out of its valid range.
    """
    if indicators < 1:
        raise ValueError("indicators must be >= 1")
    if years < 1:
        raise ValueError("years must be >= 1")
    if scenarios < 0:
        raise ValueError("scenarios must be >= 0")
    if rows < 1:
        raise ValueError("rows must be >= 1")

    out_dir.mkdir(parents=True, exist_ok=True)
    use_xlsx = _can_write_xlsx()
    has_scenarios = scenarios > 0

    scenarios_df = _build_scenarios(scenarios) if has_scenarios else None
    temporal_df = _build_temporal_reference(years, has_scenarios)
    description_df = _build_description(indicators, has_scenarios)
    composition_df = _build_composition(indicators)
    values_df = _build_values(indicators, temporal_df, scenarios_df, rows)

    written = [
        _write_sheet(description_df, out_dir, "descricao", use_xlsx=use_xlsx),
        _write_sheet(composition_df, out_dir, "composicao", use_xlsx=use_xlsx),
        _write_sheet(values_df, out_dir, "valores", use_xlsx=use_xlsx),
        _write_sheet(temporal_df, out_dir, "referencia_temporal", use_xlsx=use_xlsx),
    ]
    if scenarios_df is not None:
        written.append(_write_sheet(scenarios_df, out_dir, "cenarios", use_xlsx=use_xlsx))
    return written


def build_parser() -> argparse.ArgumentParser:
    """Build the command-line argument parser.

    Returns:
        argparse.ArgumentParser: The configured parser.
    """
    parser = argparse.ArgumentParser(description="Generate a synthetic, structurally valid data_validate input bundle.")
    parser.add_argument(
        "--indicators",
        type=int,
        default=10,
        help="Number of indicators. Indicator 1 is the root; the rest are its children.",
    )
    parser.add_argument(
        "--years",
        type=int,
        default=1,
        help="Number of temporal reference rows (honoured only when --scenarios > 0).",
    )
    parser.add_argument(
        "--scenarios",
        type=int,
        default=0,
        help="Number of scenario symbols. 0 means no cenarios sheet is generated.",
    )
    parser.add_argument("--rows", type=int, default=5, help="Number of data rows (the 'id' column) in valores.")
    parser.add_argument("--out", type=Path, required=True, help="Output directory for the generated bundle.")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Entry point: generate a bundle from parsed CLI arguments.

    Args:
        argv: Command-line arguments, or None to use `sys.argv[1:]`.

    Returns:
        int: 0 on success, 1 if argument validation failed.
    """
    args = build_parser().parse_args(argv)
    try:
        written = generate_fixture(args.indicators, args.years, args.scenarios, args.rows, args.out)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    print(f"Generated {len(written)} sheet(s) under {args.out}:")
    for path in written:
        print(f"  {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
